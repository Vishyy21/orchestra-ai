"""SQLAlchemy models for ORCHESTRA AI."""

from datetime import datetime
import uuid
from sqlalchemy import Column, String, Text, DateTime, ForeignKey, Integer, Boolean
from sqlalchemy.orm import declarative_base, relationship

Base = declarative_base()


def generate_uuid() -> str:
    """Generate a standard UUID string."""
    return str(uuid.uuid4())


class Task(Base):
    """Task model representing an orchestrated workflow execution request."""

    __tablename__ = "tasks"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    title = Column(String(255), nullable=False)
    description = Column(Text, nullable=False)
    status = Column(String(32), nullable=False, default="pending", index=True)  # pending, running, completed, failed
    category = Column(String(64), nullable=False, default="general", index=True)
    priority = Column(String(32), nullable=False, default="medium")  # low, medium, high, critical
    result_summary = Column(Text, nullable=True)
    error_message = Column(Text, nullable=True)
    requires_approval = Column(Boolean, default=False, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)

    # Relationships
    agent_runs = relationship("AgentRun", back_populates="task", cascade="all, delete-orphan", order_by="AgentRun.started_at")
    reports = relationship("Report", back_populates="task", cascade="all, delete-orphan")
    approvals = relationship("Approval", back_populates="task", cascade="all, delete-orphan")


class AgentRun(Base):
    """AgentRun model tracking individual agent actions within a task."""

    __tablename__ = "agent_runs"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    task_id = Column(String(36), ForeignKey("tasks.id", ondelete="CASCADE"), nullable=False, index=True)
    agent_name = Column(String(64), nullable=False, index=True)  # Planner, Researcher, Coder, Verifier
    status = Column(String(32), nullable=False, default="pending")  # pending, running, completed, failed
    input_data = Column(Text, nullable=True)  # JSON or text payload
    output_data = Column(Text, nullable=True)  # JSON or text response
    started_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    completed_at = Column(DateTime, nullable=True)
    execution_time_ms = Column(Integer, nullable=True)

    # Relationships
    task = relationship("Task", back_populates="agent_runs")


class Report(Base):
    """Report model for synthesized intelligence artifacts generated by agents."""

    __tablename__ = "reports"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    task_id = Column(String(36), ForeignKey("tasks.id", ondelete="SET NULL"), nullable=True, index=True)
    title = Column(String(255), nullable=False)
    content = Column(Text, nullable=False)
    category = Column(String(64), nullable=False, default="general")
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)

    # Relationships
    task = relationship("Task", back_populates="reports")


class Document(Base):
    """Document model representing knowledge base items uploaded for RAG."""

    __tablename__ = "documents"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    filename = Column(String(255), nullable=False)
    file_path = Column(String(512), nullable=False)
    file_size = Column(Integer, nullable=False)
    mime_type = Column(String(128), nullable=False, default="application/octet-stream")
    indexed = Column(Boolean, default=False, nullable=False)
    chunk_count = Column(Integer, default=0, nullable=False)
    file_hash = Column(String(64), nullable=True, index=True)
    uploaded_at = Column(DateTime, default=datetime.utcnow, nullable=False)


class Approval(Base):
    """Approval model for human-in-the-loop action authorization."""

    __tablename__ = "approvals"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    task_id = Column(String(36), ForeignKey("tasks.id", ondelete="CASCADE"), nullable=False, index=True)
    agent_name = Column(String(64), nullable=False)
    action_type = Column(String(64), nullable=False)  # code_execution, file_mutation, network_access
    description = Column(Text, nullable=False)
    status = Column(String(32), default="pending", nullable=False)  # pending, approved, rejected
    payload = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    decided_at = Column(DateTime, nullable=True)

    # Relationships
    task = relationship("Task", back_populates="approvals")
